// Regenerates games/rareton/villager-art.ts from the public on-chain artwork registry.
// Usage: node scripts/bake-villagers.mjs
import { writeFile } from "node:fs/promises";
import { createFriendReader } from "@rarefriends/friendsdk/sprites";

const ids = [21n, 77n, 3n, 150n];
const reader = createFriendReader();
const lines = [];
for (const id of ids) {
  const art = await reader.read(id);
  lines.push(`  "${id}": { familyId: ${art.familyId}, seed: ${art.seed}, frames: [\n${art.frames.map(f => `    0x${f.toString(16)}n,`).join("\n")}\n  ] },`);
}
await writeFile(new URL("../games/rareton/villager-art.ts", import.meta.url), `// Generated by scripts/bake-villagers.mjs from the public Rare Friends artwork registry
// on Robinhood Chain (4663). Artwork use follows the FriendSDK NOTICE.md.
export const VILLAGER_ART: Readonly<Record<string, { familyId: number; seed: number; frames: readonly bigint[] }>> = {
${lines.join("\n")}
};
`);
console.log("Baked", ids.join(", "));
